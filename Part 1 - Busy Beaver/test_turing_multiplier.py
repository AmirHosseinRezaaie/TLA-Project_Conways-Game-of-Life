if __name__ == "__main__":
    print_states(transitions)
    machine = TuringMachine(
        transitions,
        start_state='q0',
        accept_state='q12'
    )

    def run(input_):
        w = input_
        print("Input:",w)
        print("Accepted" if machine.accepts(w) else "Rejected")
        machine.debug(w, step_limit=1000)

        print()

    # SHOULD ACCEPT
    run("110111")
    # outputs 111111

    # SHOULD ACCEPT
    run("11101111")
